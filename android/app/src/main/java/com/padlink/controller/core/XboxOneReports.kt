package com.padlink.controller.core

import com.padlink.controller.ui.screens.controller.ControllerState
import java.nio.ByteBuffer
import java.nio.ByteOrder
import kotlin.math.roundToInt

/**
 * Original Xbox One S Bluetooth Classic, compact ten-button/Windows layout.
 * Reference: atar-axis/xpadneo docs/descriptors/xb1s_windows.md (306 bytes,
 * excluding its trailing non-HID NUL). This is not the USB GIP or BLE protocol.
 * Report IDs are supplied separately to Android's sendReport/replyReport APIs.
 */
object XboxOneReports {
    const val INPUT_ID = 1
    const val INPUT_SIZE = 15
    const val GUIDE_ID = 2
    const val RUMBLE_ID = 3
    const val RUMBLE_SIZE = 8
    const val BATTERY_ID = 4

    val descriptor: ByteArray get() = intArrayOf(
        0x05,0x01, 0x09,0x05, 0xa1,0x01, 0x85,0x01,
        // Left stick: unsigned 16-bit X/Y, center 32768.
        0x09,0x01, 0xa1,0x00, 0x09,0x30, 0x09,0x31, 0x15,0x00,
        0x27,0xff,0xff,0x00,0x00, 0x95,0x02, 0x75,0x10, 0x81,0x02, 0xc0,
        // Right stick: unsigned 16-bit Rx/Ry.
        0x09,0x01, 0xa1,0x00, 0x09,0x33, 0x09,0x34, 0x15,0x00,
        0x27,0xff,0xff,0x00,0x00, 0x95,0x02, 0x75,0x10, 0x81,0x02, 0xc0,
        // Triggers: independent 10-bit Z/Rz plus six zero padding bits each.
        0x05,0x01, 0x09,0x32, 0x15,0x00, 0x26,0xff,0x03, 0x95,0x01,
        0x75,0x0a, 0x81,0x02, 0x15,0x00, 0x25,0x00, 0x75,0x06, 0x95,0x01, 0x81,0x03,
        0x05,0x01, 0x09,0x35, 0x15,0x00, 0x26,0xff,0x03, 0x95,0x01,
        0x75,0x0a, 0x81,0x02, 0x15,0x00, 0x25,0x00, 0x75,0x06, 0x95,0x01, 0x81,0x03,
        // Hat: 1..8 clockwise from up; 0 is the null/neutral position.
        0x05,0x01, 0x09,0x39, 0x15,0x01, 0x25,0x08, 0x35,0x00, 0x46,0x3b,0x01,
        0x66,0x14,0x00, 0x75,0x04, 0x95,0x01, 0x81,0x42, 0x75,0x04, 0x95,0x01,
        0x15,0x00, 0x25,0x00, 0x35,0x00, 0x45,0x00, 0x65,0x00, 0x81,0x03,
        // A/B/X/Y/LB/RB/View/Menu/L3/R3, followed by six zero padding bits.
        0x05,0x09, 0x19,0x01, 0x29,0x0a, 0x15,0x00, 0x25,0x01, 0x75,0x01,
        0x95,0x0a, 0x81,0x02, 0x15,0x00, 0x25,0x00, 0x75,0x06, 0x95,0x01, 0x81,0x03,
        // Guide: separate one-bit System Main Menu input report.
        0x05,0x01, 0x09,0x80, 0x85,0x02, 0xa1,0x00, 0x09,0x85, 0x15,0x00, 0x25,0x01,
        0x95,0x01, 0x75,0x01, 0x81,0x02, 0x15,0x00, 0x25,0x00,
        0x75,0x07, 0x95,0x01, 0x81,0x03, 0xc0,
        // Rumble: enable mask, four motor magnitudes, duration, delay, loop count.
        0x05,0x0f, 0x09,0x21, 0x85,0x03, 0xa1,0x02, 0x09,0x97, 0x15,0x00, 0x25,0x01,
        0x75,0x04, 0x95,0x01, 0x91,0x02, 0x15,0x00, 0x25,0x00, 0x75,0x04, 0x95,0x01, 0x91,0x03,
        0x09,0x70, 0x15,0x00, 0x25,0x64, 0x75,0x08, 0x95,0x04, 0x91,0x02,
        0x09,0x50, 0x66,0x01,0x10, 0x55,0x0e, 0x15,0x00, 0x26,0xff,0x00,
        0x75,0x08, 0x95,0x01, 0x91,0x02, 0x09,0xa7, 0x15,0x00, 0x26,0xff,0x00,
        0x75,0x08, 0x95,0x01, 0x91,0x02, 0x65,0x00, 0x55,0x00, 0x09,0x7c,
        0x15,0x00, 0x26,0xff,0x00, 0x75,0x08, 0x95,0x01, 0x91,0x02, 0xc0,
        // Battery Strength: one byte, with Xbox battery source/level flags.
        0x85,0x04, 0x05,0x06, 0x09,0x20, 0x15,0x00, 0x26,0xff,0x00,
        0x75,0x08, 0x95,0x01, 0x81,0x02, 0xc0,
    ).map(Int::toByte).toByteArray()

    private fun axis(value: Float): Short {
        if (!value.isFinite()) return 0x8000.toShort()
        val clamped = value.coerceIn(-1f, 1f)
        val signed = (clamped * if (clamped < 0) 32768f else 32767f).roundToInt()
        return (signed + 32768).toShort()
    }

    private fun trigger(value: Float): Short = if (!value.isFinite()) 0 else
        (value.coerceIn(0f, 1f) * 1023f).roundToInt().toShort()

    fun input(state: ControllerState): ByteArray {
        // Internal bit 8 is Guide; Xbox's main report omits it and shifts L3/R3 down.
        val buttons = (state.buttons and 0xff) or ((state.buttons ushr 1) and 0x300)
        val genericHat = ControllerReports.hat(state.buttons)
        val hat = if (genericHat == 8) 0 else genericHat + 1
        return ByteBuffer.allocate(INPUT_SIZE).order(ByteOrder.LITTLE_ENDIAN)
            .putShort(axis(state.leftStick.x)).putShort(axis(state.leftStick.y))
            .putShort(axis(state.rightStick.x)).putShort(axis(state.rightStick.y))
            .putShort(trigger(state.leftTrigger)).putShort(trigger(state.rightTrigger))
            .put(hat.toByte()).putShort(buttons.toShort()).array()
    }

    fun guide(state: ControllerState): ByteArray = byteArrayOf(if (state.buttons and (1 shl 8) != 0) 1 else 0)

    /** Xbox reports four coarse levels and a power-source flag, not a percentage. */
    fun battery(percent: Int, charging: Boolean): ByteArray {
        val level = when (percent.coerceIn(0, 100)) {
            in 0..10 -> 0
            in 11..40 -> 1
            in 41..70 -> 2
            else -> 3
        }
        return byteArrayOf((level or if (charging) 0 else 0x04).toByte())
    }
}
